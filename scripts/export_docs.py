"""Regenerate the machine-derived docs from the code, so documentation can never drift from reality.

    python scripts/export_docs.py        (run from the repo root, using the backend virtualenv)

Writes:
    docs/schema.sql     CREATE TABLE statements for SQLite (the default) and PostgreSQL
    docs/erd.mmd        Mermaid entity-relationship diagram (rendered by GitHub inside docs/DATABASE.md)
    docs/openapi.json   The full REST API contract (same data Swagger UI shows at /docs)
"""
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BACKEND = ROOT / "backend"
DOCS = ROOT / "docs"
sys.path.insert(0, str(BACKEND))
os.chdir(BACKEND)
os.environ["DATABASE_URL"] = "sqlite://"  # never touch a real database from this script
os.environ.setdefault("JWT_SECRET", "docs-generation-only-secret-0123456789abcdef")

from sqlalchemy.dialects import postgresql, sqlite  # noqa: E402
from sqlalchemy.schema import CreateIndex, CreateTable  # noqa: E402

from app import models  # noqa: E402,F401  (registers every table)
from app.database.base import Base  # noqa: E402
from app.main import app  # noqa: E402

DOCS.mkdir(exist_ok=True)


def schema_sql() -> str:
    out = ["-- LeadFlow AI database schema (generated by scripts/export_docs.py - do not edit by hand)\n"]
    for title, dialect in (("SQLite (default)", sqlite.dialect()), ("PostgreSQL (migration target)", postgresql.dialect())):
        out.append(f"\n-- ============================================================\n-- {title}\n-- ============================================================\n")
        for table in Base.metadata.sorted_tables:
            out.append(str(CreateTable(table).compile(dialect=dialect)).strip() + ";\n")
            for index in sorted(table.indexes, key=lambda i: i.name or ""):
                out.append(str(CreateIndex(index).compile(dialect=dialect)).strip() + ";\n")
            out.append("")
    return "\n".join(out)


def erd() -> str:
    lines = ["erDiagram"]
    for table in Base.metadata.sorted_tables:
        for fk in table.foreign_keys:
            parent, child = fk.column.table.name, table.name
            parent_side = "|o" if fk.parent.nullable else "||"  # |o = parent optional, || = parent required
            child_side = "o|" if fk.parent.unique else "o{"  # o| = at most one child (UNIQUE FK), o{ = many children
            lines.append(f'    {parent} {parent_side}--{child_side} {child} : "{fk.parent.name}"')
    for table in Base.metadata.sorted_tables:
        lines.append(f"    {table.name} {{")
        for col in table.columns:
            kind = str(col.type).split("(")[0].replace(" ", "_") or "TEXT"
            marks = []
            if col.primary_key:
                marks.append("PK")
            if col.foreign_keys:
                marks.append("FK")
            if col.unique and not col.primary_key:
                marks.append("UK")
            lines.append(f"        {kind} {col.name} {' '.join(marks)}".rstrip())
        lines.append("    }")
    return "\n".join(lines) + "\n"


(DOCS / "schema.sql").write_text(schema_sql(), encoding="utf-8")
(DOCS / "erd.mmd").write_text(erd(), encoding="utf-8")
(DOCS / "openapi.json").write_text(json.dumps(app.openapi(), indent=2, ensure_ascii=False), encoding="utf-8")
tables = [t.name for t in Base.metadata.sorted_tables]
print(f"wrote docs/schema.sql ({len(tables)} tables: {', '.join(tables)}), docs/erd.mmd, docs/openapi.json ({len(app.openapi()['paths'])} paths)")
